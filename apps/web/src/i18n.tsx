const context = createContext<{
  language: Language;
  setLanguage: (value: Language) => void;
  t: (key: TranslationKey) => string;
}>(null!);
export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setState] = useState<Language>(() =>
    localStorage.getItem("minemate.language") === "de" ||
    (!localStorage.getItem("minemate.language") &&
      navigator.language.startsWith("de"))
      ? "de"
      : "en",
  );
  document.documentElement.lang = language;
  const setLanguage = (v: Language) => {
    localStorage.setItem("minemate.language", v);
    setState(v);
    document.documentElement.lang = v;
  };
  return (
    <context.Provider
      value={{
        language,
        setLanguage,
        t: (key) => messages[key][language === "en" ? 0 : 1],
      }}
    >
      {children}
    </context.Provider>
  );
}
export const useI18n = () => useContext(context);
